#!/usr/bin/env python3
"""passive_listen.py - listen on the port and write NOTHING AT ALL.

Context, and why this exists
----------------------------
Every catcher written tonight ended its session with SAHARA_RESET (0x07). The
timing in the logs is unambiguous:

    [ 34.954]   no HELLO in 8 s
    [ 34.955]   attempt finished without data      <- session ends
    [ 34.971]   port disappeared after 14 ms       <- 16 ms later

The port vanishes 16 ms after the session closes. That is not the tablet
cycling: it is the reset we just sent re-enumerating the interface. The
"boot loop" of this device, at least in this session, is being generated by the
observer - the exact trap already recorded in docs/23-no-boot-loop.md, repeated.

So this tool opens the port, reads, and closes WITHOUT writing a single byte.
If the port still disappears, the cause is the device. If it stays, the cause
was ours.

Usage
    python passive_listen.py --port COM10 --seconds 60
"""
from __future__ import annotations

import argparse
import struct
import sys
import time

import serial
import serial.tools.list_ports

T0 = time.time()


def log(m: str = "") -> None:
    print(f"[{time.time() - T0:7.3f}] {m}", flush=True)


def present(port: str) -> bool:
    try:
        return any(p.device.upper() == port.upper()
                   for p in serial.tools.list_ports.comports())
    except Exception:  # noqa: BLE001
        return False


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--port", default="COM10")
    ap.add_argument("--seconds", type=float, default=60.0)
    ap.add_argument("--wait-appear", type=float, default=0.0,
                    help="wait this long for the port to appear before opening")
    args = ap.parse_args()
    port = args.port.upper()

    log("=" * 70)
    log(f"#  passive_listen - read only, zero bytes written, {args.seconds:.0f}s")
    log("=" * 70)

    if args.wait_appear > 0:
        log(f"  waiting up to {args.wait_appear:.0f}s for {port}")
        end = time.time() + args.wait_appear
        while time.time() < end and not present(port):
            time.sleep(0.002)
        if not present(port):
            log("  port never appeared")
            return 1
        log(f"  appeared at t={time.time() - T0:.2f}s")

    if not present(port):
        log(f"  {port} not present")
        return 1

    try:
        ser = serial.Serial(port, 115200, timeout=0.1)
    except Exception as err:  # noqa: BLE001
        log(f"  open failed: {type(err).__name__}: {err}")
        return 1
    log("  open (DTR/RTS as pyserial sets them)")

    got = bytearray()
    end = time.time() + args.seconds
    vanished = None
    while time.time() < end:
        try:
            chunk = ser.read(512)
        except Exception as err:  # noqa: BLE001
            log(f"  read error: {type(err).__name__}: {err}")
            break
        if chunk:
            got += chunk
            log(f"  +{len(chunk)} B  {chunk[:32].hex(' ')}")
        if not present(port):
            vanished = time.time() - T0
            log(f"  PORT DISAPPEARED at t={vanished:.2f}s with no write from us")
            break

    try:
        ser.close()
    except Exception:  # noqa: BLE001
        pass

    log("")
    log(f"  total bytes: {len(got)}")
    if len(got) >= 8:
        cmd, ln = struct.unpack_from("<II", got, 0)
        names = {0x01: "HELLO_REQ", 0x02: "HELLO_RSP", 0x04: "END_TRANSFER",
                 0x09: "MEMORY_DEBUG", 0x10: "MEMORY_DEBUG_64", 0x08: "RESET_RSP"}
        log(f"  cmd={cmd:#x} ({names.get(cmd, 'other')}) len={ln}")
        if cmd == 0x01 and ln >= 0x30:
            log(f"  *** ver={struct.unpack_from('<I', got, 8)[0]} "
                f"mode={struct.unpack_from('<I', got, 20)[0]} ***")
    else:
        log("  silence")
    if vanished is None:
        log("  the port stayed up for the whole window -> opening did not disturb it")
    return 0 if got else 1


if __name__ == "__main__":
    sys.exit(main())
